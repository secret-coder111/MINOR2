// Reuse the exact extension URL extractor; no borrowed document/DOM features.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const root = path.resolve(__dirname, '..');
const files = ['shared/feature-schema.js', 'shared/constants.js', 'shared/public-suffix.js',
  'shared/domain-utils.js', 'content/url-features.js', 'shared/model-policy.js'];
const source = files.map(name => fs.readFileSync(path.join(root, 'extension/src', name), 'utf8')).join('\n');
fs.writeFileSync(path.join(root, 'extension/demo/url-core.js'), '// Generated by npm run build:url-checker.\n' + source);
console.log(JSON.stringify({ files: files.length, urlExtractorBundleSha256: crypto.createHash('sha256').update(source).digest('hex') }));
