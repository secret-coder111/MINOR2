// Regenerate the pinned offline ICANN + PRIVATE PSL from npm's installed tldts.
// No downloads occur here. Review the dependency update and rerun tests afterwards.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const { domainToASCII } = require('node:url');
const root = path.resolve(__dirname, '..');
const packageRoot = path.dirname(require.resolve('tldts/package.json'));
const version = require(path.join(packageRoot, 'package.json')).version;
const trie = require(path.join(packageRoot, 'dist/cjs/src/data/trie.js'));
const labels = [];
let offset = 0;
for (const length of trie.edgeLength) {
  labels.push(trie.labelText.slice(offset, offset + length));
  offset += length;
}
const rules = new Set();
function walk(node, suffix, exception = false) {
  if (trie.nodeFlags[node] && suffix.length) {
    // Convert the complete name: converting a numeric label such as "1" alone
    // applies WHATWG IPv4 normalization and would corrupt rules such as 1.bg.
    const rule = domainToASCII('psl.' + suffix.join('.')).slice(4);
    if (!rule) throw new Error('Invalid rule in pinned PSL');
    rules.add((exception ? '!' : '') + rule);
  }
  for (let edge = trie.edgeStart[node]; edge < trie.edgeStart[node + 1]; edge += 1) {
    walk(trie.edgeChild[edge], [labels[edge], ...suffix], exception);
  }
}
walk(trie.rulesRoot, []);
walk(trie.exceptionsRoot, [], true);
const ordered = [...rules].sort();
const data = {
  source: 'tldts (Public Suffix List, ICANN + PRIVATE)',
  version,
  rules_sha256: crypto.createHash('sha256').update(ordered.join('\n')).digest('hex'),
  rules: ordered
};
const destination = path.join(root, 'extension/src/shared');
fs.writeFileSync(path.join(destination, 'public-suffix-rules.json'), JSON.stringify(data) + '\n');
fs.writeFileSync(path.join(destination, 'public-suffix.js'),
  '// Generated by scripts/vendor-public-suffix.cjs. See THIRD_PARTY_NOTICES.md.\n'
  + '(function(g){g.PHISH_GUARD_PSL=' + JSON.stringify(data) + ';})'
  + '(typeof globalThis!=="undefined"?globalThis:self);\n');
fs.writeFileSync(path.join(destination, 'tldts-LICENSE.txt'), fs.readFileSync(path.join(packageRoot, 'LICENSE')));
console.log(`Vendored ${ordered.length} PSL rules from tldts ${version}.`);
