const assert = require('node:assert/strict');
const { scoreFeatures, getRiskLevel, normalizeFeatureVector } = require('../../src/shared/risk-score.js');
const { scoreEvidence } = require('../../src/shared/model-policy.js');
const normal = { credential_context: 1, has_password_input: 1, credential_field_count: 2 };
const phishing = { ...normal, brand_domain_mismatch: 1, cross_domain_form_action: 1 };
assert.equal(scoreFeatures(normal), scoreEvidence(normal).score);
assert.equal(scoreFeatures(phishing), 80);
assert.equal(getRiskLevel(scoreFeatures(normal)), 'legitimate');
assert.equal(getRiskLevel(scoreFeatures(phishing)), 'likely_phishing');
assert.equal(getRiskLevel(80, { warningThreshold: 90 }), 'suspicious');
const normalized = normalizeFeatureVector({ url_length: 400, hidden_iframe_count: 1, credential_field_count: Infinity });
assert.equal(normalized.url_length, 1);
assert.equal(normalized.hidden_iframe_count, 1 / 3);
assert.equal(normalized.credential_field_count, 0);
assert.equal(normalizeFeatureVector(null).url_length, 0);
console.log('Canonical scoring compatibility validation passed.');
